import { createFileRoute } from "@tanstack/react-router";
import { useMemo, useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useTable } from "@/lib/fin-data";
import { money, shortDate, titleCase } from "@/lib/format";
import {
  PageHeader,
  Panel,
  Pill,
  Metric,
  Loading,
  TableShell,
  Th,
  Td,
  AutomationNote,
} from "@/components/fin/primitives";
import { Input } from "@/components/ui/input";
import { cn } from "@/lib/utils";

export const Route = createFileRoute("/_app/accounting")({
  head: () => ({
    meta: [
      { title: "Accounting · FIN Autonomous Finance OS" },
      {
        name: "description",
        content:
          "General ledger, chart of accounts, trial balance and every journal entry FIN posted — with source document traceability.",
      },
      { property: "og:title", content: "Accounting · FIN" },
      { property: "og:description", content: "A ledger that is always closed." },
    ],
  }),
  component: Accounting,
});

const TABS = ["Journal", "Trial balance", "Chart of accounts", "Periods"] as const;

function Accounting() {
  const entries = useTable<any>("journal_entries", ["a"], (q: any) =>
    q.order("entry_date", { ascending: false }).limit(200),
  );
  const accounts = useTable<any>("accounts", ["a"], (q: any) => q.order("code"));
  const periods = useTable<any>("accounting_periods", ["a"], (q: any) => q.order("starts_on"));
  const lines = useQuery({
    queryKey: ["jel", "all"],
    queryFn: async () => {
      const { data, error } = await supabase
        .from("journal_entry_lines")
        .select("account_code,account_name,debit,credit")
        .limit(5000);
      if (error) throw new Error(error.message);
      return data ?? [];
    },
  });
  const [tab, setTab] = useState<(typeof TABS)[number]>("Journal");
  const [term, setTerm] = useState("");
  const [open, setOpen] = useState<string | null>(null);
  const detail = useQuery({
    queryKey: ["jel", open],
    enabled: !!open,
    queryFn: async () =>
      (await supabase.from("journal_entry_lines").select("*").eq("journal_entry_id", open!)).data ?? [],
  });

  const tb = useMemo(() => {
    const m = new Map<string, { code: string; name: string; debit: number; credit: number }>();
    (lines.data ?? []).forEach((l: any) => {
      const r = m.get(l.account_code) ?? { code: l.account_code, name: l.account_name, debit: 0, credit: 0 };
      r.debit += Number(l.debit);
      r.credit += Number(l.credit);
      m.set(l.account_code, r);
    });
    return Array.from(m.values()).sort((a, b) => a.code.localeCompare(b.code));
  }, [lines.data]);
  const tbDebit = tb.reduce((s, r) => s + r.debit, 0);
  const tbCredit = tb.reduce((s, r) => s + r.credit, 0);

  const all = entries.data ?? [];
  const system = all.filter((e: any) => e.source !== "manual").length;

  return (
    <>
      <PageHeader title="Accounting" subtitle="General ledger — double-entry, source-traceable, continuously closed" />

      <AutomationNote>
        {system} of the last {all.length} journal entries were generated by FIN from source documents.
        Trial balance is in balance: debits {money(tbDebit, true)} against credits {money(tbCredit, true)}.
      </AutomationNote>

      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <Metric label="Journal entries" value={String(all.length)} hint="Most recent 200" />
        <Metric label="Auto-posted" value={`${all.length ? ((system / all.length) * 100).toFixed(0) : 0}%`} hint="No human touch" />
        <Metric label="Accounts" value={String((accounts.data ?? []).length)} hint="Chart of accounts" />
        <Metric label="Open periods" value={String((periods.data ?? []).filter((p: any) => !p.is_closed).length)} hint="FY2026" />
      </div>

      <div className="flex flex-wrap items-center gap-2 border-b border-border pb-2">
        {TABS.map((t) => (
          <button
            key={t}
            onClick={() => setTab(t)}
            className={cn(
              "rounded-sm px-2.5 py-1.5 text-[13px]",
              tab === t ? "bg-secondary font-medium" : "text-muted-foreground hover:bg-secondary/60",
            )}
          >
            {t}
          </button>
        ))}
        <Input
          value={term}
          onChange={(e) => setTerm(e.target.value)}
          placeholder="Filter…"
          className="ml-auto h-8 w-[220px] text-[13px]"
        />
      </div>

      {entries.isLoading ? (
        <Loading rows={12} />
      ) : tab === "Journal" ? (
        <Panel>
          <TableShell>
            <thead>
              <tr>
                <Th>Entry</Th>
                <Th>Date</Th>
                <Th>Memo</Th>
                <Th>Source</Th>
                <Th>Reference</Th>
                <Th right>Debit</Th>
                <Th right>Credit</Th>
              </tr>
            </thead>
            <tbody>
              {all
                .filter((e: any) => (e.memo ?? "").toLowerCase().includes(term.toLowerCase()) || e.number.includes(term))
                .map((e: any) => (
                  <>
                    <tr
                      key={e.id}
                      onClick={() => setOpen(open === e.id ? null : e.id)}
                      className="row-hover cursor-pointer hover:bg-secondary/40"
                    >
                      <Td>
                        <span className="num font-medium">{e.number}</span>
                      </Td>
                      <Td>{shortDate(e.entry_date)}</Td>
                      <Td className="max-w-[360px] truncate">{e.memo}</Td>
                      <Td>
                        <Pill tone={e.source === "manual" ? "neutral" : "signal"}>
                          {e.source === "manual" ? "Manual" : "FIN"}
                        </Pill>
                      </Td>
                      <Td>
                        <span className="num text-xs text-muted-foreground">{e.ref_label ?? titleCase(e.ref_type)}</span>
                      </Td>
                      <Td right>{money(e.total_debit)}</Td>
                      <Td right>{money(e.total_credit)}</Td>
                    </tr>
                    {open === e.id ? (
                      <tr key={`${e.id}-d`}>
                        <td colSpan={7} className="border-b border-border bg-secondary/40 px-6 py-3">
                          {detail.isLoading ? (
                            <span className="text-xs text-muted-foreground">Loading lines…</span>
                          ) : (
                            <table className="w-full text-[12.5px]">
                              <tbody>
                                {(detail.data ?? []).map((l: any) => (
                                  <tr key={l.id}>
                                    <td className="py-1">
                                      <span className="num text-muted-foreground">{l.account_code}</span> {l.account_name}
                                    </td>
                                    <td className="py-1 text-muted-foreground">{l.description}</td>
                                    <td className="num py-1 text-right">{Number(l.debit) ? money(l.debit) : ""}</td>
                                    <td className="num w-[130px] py-1 text-right">{Number(l.credit) ? money(l.credit) : ""}</td>
                                  </tr>
                                ))}
                              </tbody>
                            </table>
                          )}
                        </td>
                      </tr>
                    ) : null}
                  </>
                ))}
            </tbody>
          </TableShell>
        </Panel>
      ) : tab === "Trial balance" ? (
        <Panel title="Trial balance" description="Year to date, all posted entries">
          <TableShell>
            <thead>
              <tr>
                <Th>Code</Th>
                <Th>Account</Th>
                <Th right>Debit</Th>
                <Th right>Credit</Th>
                <Th right>Net</Th>
              </tr>
            </thead>
            <tbody>
              {tb.map((r) => (
                <tr key={r.code}>
                  <Td>
                    <span className="num">{r.code}</span>
                  </Td>
                  <Td>{r.name}</Td>
                  <Td right>{money(r.debit)}</Td>
                  <Td right>{money(r.credit)}</Td>
                  <Td right>{money(r.debit - r.credit)}</Td>
                </tr>
              ))}
              <tr className="font-medium">
                <Td>{""}</Td>
                <Td>Total</Td>
                <Td right>{money(tbDebit)}</Td>
                <Td right>{money(tbCredit)}</Td>
                <Td right>{money(tbDebit - tbCredit)}</Td>
              </tr>
            </tbody>
          </TableShell>
        </Panel>
      ) : tab === "Chart of accounts" ? (
        <Panel>
          <TableShell>
            <thead>
              <tr>
                <Th>Code</Th>
                <Th>Name</Th>
                <Th>Type</Th>
                <Th>Subtype</Th>
              </tr>
            </thead>
            <tbody>
              {(accounts.data ?? [])
                .filter((a: any) => a.name.toLowerCase().includes(term.toLowerCase()) || a.code.includes(term))
                .map((a: any) => (
                  <tr key={a.id}>
                    <Td>
                      <span className="num">{a.code}</span>
                    </Td>
                    <Td className={a.is_group ? "font-medium" : undefined}>{a.name}</Td>
                    <Td>{titleCase(a.type)}</Td>
                    <Td>
                      <span className="text-muted-foreground">{titleCase(a.subtype)}</span>
                    </Td>
                  </tr>
                ))}
            </tbody>
          </TableShell>
        </Panel>
      ) : (
        <Panel title="Accounting periods">
          <TableShell>
            <thead>
              <tr>
                <Th>Period</Th>
                <Th>From</Th>
                <Th>To</Th>
                <Th>Status</Th>
              </tr>
            </thead>
            <tbody>
              {(periods.data ?? []).map((p: any) => (
                <tr key={p.id}>
                  <Td>{p.name}</Td>
                  <Td>{shortDate(p.starts_on)}</Td>
                  <Td>{shortDate(p.ends_on)}</Td>
                  <Td>
                    <Pill tone={p.is_closed ? "success" : "warning"}>{p.is_closed ? "Closed" : "Open"}</Pill>
                  </Td>
                </tr>
              ))}
            </tbody>
          </TableShell>
        </Panel>
      )}
    </>
  );
}
